import React, { useEffect, useRef, useState } from 'react';
import { Bot, Check, Copy, RotateCw, Send, Sparkles, ThumbsDown, ThumbsUp, Trash2, User } from 'lucide-react';
import { useApp } from '../../context/AppContext';

const STARTERS = [
  'Help me outline a YouTube Short about my latest video.',
  'Suggest three alternative titles for a video I describe.',
  'Turn this idea into a concise video script.',
];

export const GeminiStudio: React.FC = () => {
  const {
    chatMessages,
    sendMessage,
    isAiGenerating,
    toggleLikeMessage,
    toggleDislikeMessage,
    clearChat,
    addToast,
  } = useApp();
  const [prompt, setPrompt] = useState('');
  const [copied, setCopied] = useState<string | null>(null);
  const bottomRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [chatMessages, isAiGenerating]);

  const submit = async (event?: React.FormEvent) => {
    event?.preventDefault();
    if (!prompt.trim() || isAiGenerating) return;
    const current = prompt;
    setPrompt('');
    await sendMessage(current);
  };

  const regenerate = async () => {
    const lastPrompt = [...chatMessages].reverse().find((message) => message.sender === 'user')?.text;
    if (lastPrompt) await sendMessage(`${lastPrompt}\nPlease provide a different alternative.`);
  };

  const copy = async (id: string, text: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(id);
      window.setTimeout(() => setCopied(null), 1500);
    } catch {
      addToast('Copy failed', 'Clipboard access was denied by the browser.', 'error');
    }
  };

  return (
    <div className="h-full min-h-0 flex flex-col bg-white dark:bg-[#131314]">
      <header className="flex items-center justify-between gap-2 border-b border-slate-200 px-3 py-3 dark:border-[#282a2c] sm:gap-3 sm:px-4 md:px-8">
        <div className="flex items-center gap-2 text-sm font-semibold"><Sparkles className="w-4 h-4 text-indigo-500" /> Gemini Studio</div>
        <div className="flex items-center gap-2">
          <span className="hidden text-xs text-slate-500 lg:inline">Gemini 3.8 Flash · 3.1 Flash-Lite fallback</span>
          <button onClick={clearChat} className="inline-flex items-center gap-1 rounded-lg bg-slate-100 px-2 py-2 text-xs dark:bg-[#282a2c] sm:px-2.5"><Trash2 className="h-3.5 w-3.5" /><span className="hidden sm:inline">Clear</span></button>
        </div>
      </header>

      <div className="flex-1 overflow-y-auto px-4 md:px-8 py-6">
        <div className="max-w-3xl mx-auto space-y-6">
          {chatMessages.length === 0 && (
            <div className="py-16 space-y-5 text-center">
              <Sparkles className="w-10 h-10 mx-auto text-indigo-500" />
              <h1 className="text-2xl font-bold">Ask Gemini</h1>
              <p className="text-sm text-slate-500">Responses are generated by the backend using your configured Gemini API key. No sample chat is loaded.</p>
              <div className="flex flex-wrap justify-center gap-2">
                {STARTERS.map((starter) => <button key={starter} onClick={() => setPrompt(starter)} className="px-3 py-2 rounded-xl border border-slate-200 dark:border-[#282a2c] text-xs hover:bg-slate-50 dark:hover:bg-[#1e1f20]">{starter}</button>)}
              </div>
            </div>
          )}
          {chatMessages.map((message) => (
            <article key={message.id} className={`flex gap-3 ${message.sender === 'user' ? 'justify-end' : 'justify-start'}`}>
              {message.sender === 'gemini' && <div className="w-8 h-8 rounded-full bg-indigo-500/10 text-indigo-500 flex items-center justify-center shrink-0"><Bot className="w-4 h-4" /></div>}
              <div className={`max-w-[90%] break-words rounded-2xl p-3 sm:max-w-[85%] sm:p-4 ${message.sender === 'user' ? 'bg-indigo-600 text-white' : 'bg-slate-50 dark:bg-[#1e1f20] text-slate-800 dark:text-slate-200'}`}>
                <p className="text-sm whitespace-pre-wrap break-words">{message.text}</p>
                <div className="flex items-center justify-between gap-3 mt-3 text-[10px] opacity-60">
                  <span>{message.modelUsed || message.timestamp}</span>
                  {message.sender === 'gemini' && <div className="flex gap-1">
                    <button onClick={() => toggleLikeMessage(message.id)} aria-label="Like response"><ThumbsUp className="w-3.5 h-3.5" /></button>
                    <button onClick={() => toggleDislikeMessage(message.id)} aria-label="Dislike response"><ThumbsDown className="w-3.5 h-3.5" /></button>
                    <button onClick={() => void copy(message.id, message.text)} aria-label="Copy response">{copied === message.id ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}</button>
                    <button onClick={() => void regenerate()} aria-label="Regenerate response"><RotateCw className="w-3.5 h-3.5" /></button>
                  </div>}
                </div>
              </div>
              {message.sender === 'user' && <div className="w-8 h-8 rounded-full bg-slate-200 dark:bg-[#282a2c] flex items-center justify-center shrink-0"><User className="w-4 h-4" /></div>}
            </article>
          ))}
          {isAiGenerating && <p role="status" className="text-sm text-indigo-500 animate-pulse">Waiting for Gemini…</p>}
          <div ref={bottomRef} />
        </div>
      </div>

      <form onSubmit={submit} className="mx-auto w-full max-w-3xl px-3 pb-3 sm:px-4 sm:pb-5">
        <div className="flex items-end gap-2 p-2 rounded-2xl border border-slate-200 dark:border-[#282a2c] bg-white dark:bg-[#1e1f20] shadow-lg">
          <textarea value={prompt} onChange={(event) => setPrompt(event.target.value)} onKeyDown={(event) => {
            if (event.key === 'Enter' && !event.shiftKey) {
              event.preventDefault();
              void submit();
            }
          }} rows={1} placeholder="Message Gemini…" className="max-h-32 min-w-0 flex-1 resize-y bg-transparent p-2 text-sm focus:outline-none" />
          <button type="submit" disabled={!prompt.trim() || isAiGenerating} aria-label="Send message" className="p-2 rounded-full bg-indigo-600 text-white disabled:opacity-40"><Send className="w-4 h-4" /></button>
        </div>
      </form>
    </div>
  );
};
